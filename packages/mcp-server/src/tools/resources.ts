export function readDrizzleResource(uri: string): { uri: string; mimeType: string; text: string } {
  if (uri === 'drizzle://schemas/workspace') {
    const schemaPath = resolveDefaultSchemaPath();
    if (!schemaPath) {
      return {
        uri,
        mimeType: 'application/json',
        text: JSON.stringify({ tables: [], message: 'No default workspace Drizzle schema found.' }, null, 2)
      };
    }
    const inspection = DrizzleSchemaParser.parseFile(schemaPath);
    return {
      uri,
      mimeType: 'application/json',
      text: JSON.stringify({ ...inspection, filePath: path.basename(inspection.filePath) }, null, 2)
    };
  }

  const patchMatch = /^drizzle:\/\/migrations\/patches\/([a-zA-Z0-9_-]+)\.sql$/.exec(uri);
  if (patchMatch) {
    const patch = generatedPatches.get(patchMatch[1]);
    if (!patch) {
      throw new Error(`Generated patch '${patchMatch[1]}' not found in session store.`);
    }
    return {
      uri,
      mimeType: 'application/sql',
      text: patch.sql || '-- No schema drift changes required.'
    };
  }

  const tableMatch = /^drizzle:\/\/table\/(postgresql|sqlite|mysql)\/([a-zA-Z0-9_]+)$/.exec(uri);
  if (tableMatch) {
    const schemaPath = resolveDefaultSchemaPath();
    if (!schemaPath) {
      throw new Error('No workspace Drizzle schema available to resolve table resource.');
    }
    const inspection = DrizzleSchemaParser.parseFile(schemaPath);
    const table = inspection.tables.find(t => t.name === tableMatch[2]);
    if (!table) {
      throw new Error(`Table '${tableMatch[2]}' not found in workspace Drizzle schema.`);
    }
    return {
      uri,
      mimeType: 'application/json',
      text: JSON.stringify({ requestedDialect: tableMatch[1], table }, null, 2)
    };
  }

  throw new Error(`Unsupported Drizzle resource URI: ${uri}`);
}

export function getAuditMigrationPrompt(args: Record<string, string> | undefined) {
  const dialect = args?.dialect || 'postgresql';
  const tableName = args?.tableName || 'users';
  return {
    description: `Zero-downtime migration & drift audit for '${tableName}' (${dialect})`,
    messages: [
      {
        role: 'user' as const,
        content: {
          type: 'text' as const,
          text: [
            `Audit the Drizzle table '${tableName}' for target dialect '${dialect}':`,
            `1. Call inspect_drizzle_schema on the workspace schema and review '${tableName}' foreign keys and indexes.`,
            `2. Call detect_schema_drift against live database table metadata.`,
            `3. Call generate_migration_patch with dialect='${dialect}' to synthesize an expand-only TypeScript & SQL patch.`,
            `4. Verify ruleGateStatus === 'PASSED' and criticalViolations === 0 before proposing deployment.`
          ].join('\n')
        }
      }
    ]
  };
}

export function completeArgument(params: {
  ref: { type: string; name?: string; uri?: string };
  argument: { name: string; value: string };
}): { values: string[]; total: number; hasMore: boolean } {
  const prefix = (params.argument.value || '').toLowerCase();
  let candidates: string[] = [];

  if (params.argument.name === 'dialect') {
    candidates = ['postgresql', 'sqlite', 'mysql'];
  } else if (params.argument.name === 'tableName') {
    const schemaPath = resolveDefaultSchemaPath();
    if (schemaPath) {
      const inspection = DrizzleSchemaParser.parseFile(schemaPath);
      candidates = inspection.tables.map(t => t.name);
    }
  } else if (params.argument.name === 'migrationName') {
    candidates = Array.from(generatedPatches.keys());
  }

  const filtered = candidates.filter(c => c.toLowerCase().startsWith(prefix));
  return {
    values: filtered.slice(0, 20),
    total: filtered.length,
    hasMore: filtered.length > 20
  };
}
