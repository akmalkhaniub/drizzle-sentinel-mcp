import * as fs from 'fs';
import * as path from 'path';
import { DrizzleSchemaParser } from '../services/drizzle-parser.js';
import { resolveSafeWorkspacePath } from '../security.js';

interface StoredPatch {
  sql: string;
  typescript: string;
  createdAt: string;
}

const generatedPatches = new Map<string, StoredPatch>();

export function registerGeneratedPatch(migrationName: string, sql: string, typescript: string): string {
  generatedPatches.set(migrationName, {
    sql,
    typescript,
    createdAt: new Date().toISOString()
  });
  return `drizzle://migrations/patches/${migrationName}.sql`;
}

export function resolveDefaultSchemaPath(): string | null {
  const candidates = [
    process.env.DRIZZLE_SENTINEL_SCHEMA_PATH,
    'apps/demo-service/src/db/schema.ts',
    'src/db/schema.ts'
  ].filter((c): c is string => Boolean(c));

  for (const candidate of candidates) {
    try {
      const safe = resolveSafeWorkspacePath(candidate, { allowedExtensions: ['.ts', '.mts', '.cts'] });
      if (fs.existsSync(safe)) {
        return safe;
      }
    } catch {
      // Ignore invalid/out-of-workspace defaults
    }
  }
  return null;
}

export function listWorkspaceResources() {
  const resources: Array<{ uri: string; name: string; description: string; mimeType: string }> = [
    {
      uri: 'drizzle://schemas/workspace',
      name: 'Workspace Drizzle Schema Summary',
      description: 'Parsed JSON AST summary of the active workspace Drizzle schema.',
      mimeType: 'application/json'
    }
  ];

  for (const [name] of generatedPatches.entries()) {
    resources.push({
      uri: `drizzle://migrations/patches/${name}.sql`,
      name: `${name}.sql`,
      description: 'Non-destructive migration SQL patch generated by generate_migration_patch.',
      mimeType: 'application/sql'
    });
  }

  return resources;
}

